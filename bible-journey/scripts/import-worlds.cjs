// Import the existing chapter maps without changing the parent game.
const fs = require('node:fs');
const path = require('node:path');
const root = process.cwd();
const source = path.resolve(root, '..');
const sharp = require(path.join(root, 'node_modules/sharp'));
const { lifeHeroesForLanguage } = require(path.join(source, 'src/lib/life/content.ts'));
const { lifeMap, lifeBonusSpots, LIFE_WORLD } = require(path.join(source, 'src/lib/life/world.ts'));
async function main() {
  fs.mkdirSync(path.join(root, 'assets/worlds'), { recursive: true });
  const worlds = {};
  for (const hero of lifeHeroesForLanguage('en')) for (const chapter of hero.chapters) {
    const map = lifeMap(chapter.mapId);
    const image = `world-${chapter.mapId}.png`;
    await sharp(path.join(source, 'public/art/life', `world-${chapter.mapId}.svg`))
      .resize(1024, 704, { kernel: 'nearest' }).png().toFile(path.join(root, 'assets/worlds', image));
    worlds[chapter.storyId] = {
      id: chapter.mapId, image, width: LIFE_WORLD.width, height: LIFE_WORLD.height,
      start: map.start, checkpoint: map.checkpoint, movement: map.movement,
      water: map.water, blocked: map.blocked, navigable: map.navigable,
      bonusSpots: lifeBonusSpots(chapter.mapId),
    };
  }
  fs.writeFileSync(path.join(root, 'content/worlds.json'), JSON.stringify(worlds, null, 2) + '\n');
  fs.writeFileSync(path.join(root, 'content/world-images.generated.ts'),
    '// Generated by scripts/import-worlds.cjs. Original map artwork from the parent game.\n' +
    'export const worldImages: Record<string, number> = {\n' +
    Object.entries(worlds).map(([id, map]) => `  ${JSON.stringify(id)}: require("../assets/worlds/${map.image}"),`).join('\n') + '\n};\n');
  console.log(`Imported ${Object.keys(worlds).length} original chapter maps and 54 reachable bonus locations.`);
}
main().catch(error => { console.error(error); process.exitCode = 1; });
